def heartbeat_times():
    """可见/可闻的心跳（lub 时刻）。"""
    beats = [float(t) for t in range(1, 16)]               # 60 bpm
    beats += [16.0 + 0.5 * i for i in range(0, 8)]          # 加速到 120 bpm，与鼓融合
    beats += [96.0 + 1.0 * i for i in range(0, 8)]          # 第二章前的呼吸段
    beats += [180.0 + 1.0 * i for i in range(0, 12)]        # 尾声
    return beats
