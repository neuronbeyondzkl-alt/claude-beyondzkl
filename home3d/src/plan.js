// 房间名到对象
export const ROOM = Object.fromEntries(ROOMS.map((r) => [r.id, r]));

export function roomArea(room) {
  return room.rects.reduce((s, [x0, z0, x1, z1]) => s + (x1 - x0) * (z1 - z0), 0) / 1e6;
}

export function roomBounds(room) {
  let x0 = Infinity, z0 = Infinity, x1 = -Infinity, z1 = -Infinity;
  for (const r of room.rects) {
    x0 = Math.min(x0, r[0]); z0 = Math.min(z0, r[1]);
    x1 = Math.max(x1, r[2]); z1 = Math.max(z1, r[3]);
  }
  return { x0, z0, x1, z1, cx: (x0 + x1) / 2, cz: (z0 + z1) / 2, w: x1 - x0, d: z1 - z0 };
}

export function roomAt(x, z) {
  for (const room of ROOMS) {
    for (const [x0, z0, x1, z1] of room.rects) {
      if (x >= x0 && x <= x1 && z >= z0 && z <= z1) return room;
    }
  }
  return null;
}
